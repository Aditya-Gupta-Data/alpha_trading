# MANUAL OFFLINE TOOL — writes docs/BRANCHES.md: every branch's work that is not yet in main (run by wrap_session.sh).
"""Reads git only; never touches data/ or logs/. The hand-written part of BRANCHES.md above the AUTO marker is kept."""
import argparse
import re
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "BRANCHES.md"
BEGIN = "<!-- BEGIN AUTO: scripts/branch_report.py -->"
END = "<!-- END AUTO -->"
MAX_FILES = 25
BODY_LINES = 8
STALE_DAYS = 30

DEFAULT_HEAD = """# BRANCHES.md — work that is NOT in `main` yet

`main` is what the docs describe and what gets deployed. This page lists
everything else: branches with commits `main` does not have, and checkouts
with uncommitted edits. Nothing listed here is running on the VM, the Mini PC
or the dashboard box unless HANDOVER.md says it was deployed from that branch.

The section below the marker is regenerated by `python3 scripts/branch_report.py`
(and by `bash scripts/wrap_session.sh`). Edit only above the marker.
"""


def git(args, root=ROOT, check=True):
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def decision_rows(text):
    rows = {}
    for line in text.splitlines():
        m = re.match(r"^\|\s*(\d{2,3})\s*\|\s*(.*)", line)
        if m:
            t = re.match(r"\*\*(.+?)\*\*", m.group(2))
            rows[int(m.group(1))] = (t.group(1) if t else m.group(2))[:160]
    return rows


def decision_changes(branch_text, main_text):
    """New and colliding decision numbers on a branch, versus main."""
    b, m = decision_rows(branch_text), decision_rows(main_text)
    new = sorted(n for n in b if n not in m)
    clash = sorted(n for n in b if n in m and b[n][:60] != m[n][:60])
    return [(n, b[n]) for n in new], [(n, b[n], m[n]) for n in clash]


def splice(existing, auto):
    """Replace the AUTO section, keeping the hand-written head."""
    if existing and BEGIN in existing:
        head = existing.split(BEGIN, 1)[0].rstrip() + "\n"
    else:
        head = DEFAULT_HEAD
    return f"{head}\n{BEGIN}\n\n{auto.strip()}\n\n{END}\n"


def list_branches(root, main):
    local = git(["for-each-ref", "--format=%(refname:short)", "refs/heads"], root).split()
    remote = [r for r in git(["for-each-ref", "--format=%(refname:short)", "refs/remotes"], root).split()
              if not r.endswith("/HEAD") and "/" in r]
    main_names = {main, main.split("/", 1)[-1]}
    out, seen = [], set()
    for ref in local + remote:
        name = ref.split("/", 1)[1] if ref in remote and "/" in ref else ref
        if name in main_names or name in seen or ref in main_names:
            continue
        seen.add(name)
        where = []
        if name in local:
            where.append("local")
        if any(r.split("/", 1)[-1] == name for r in remote):
            where.append("origin")
        out.append((name, ref, where))
    return out


def worktrees(root):
    trees, cur = [], {}
    for line in git(["worktree", "list", "--porcelain"], root).splitlines():
        if line.startswith("worktree "):
            cur = {"path": line[9:], "branch": "(detached)"}
            trees.append(cur)
        elif line.startswith("branch "):
            cur["branch"] = line[7:].replace("refs/heads/", "")
    return trees


def branch_section(root, main, name, ref, where, wt_by_branch, main_decisions, today):
    cherry = git(["cherry", main, ref], root).split("\n")
    unmerged = [l[2:] for l in cherry if l.startswith("+ ")]
    equivalent = [l for l in cherry if l.startswith("- ")]
    if not unmerged:
        return None
    last = git(["log", "-1", "--format=%ad|%an", "--date=short", ref], root).strip().split("|")
    behind = git(["rev-list", "--count", f"{ref}..{main}"], root).strip()
    age = (today - datetime.strptime(last[0], "%Y-%m-%d").date()).days
    status = "STALE" if age > STALE_DAYS else "ACTIVE"
    lines = [f"### `{name}` — {status}",
             "",
             f"- **Where:** {', '.join(where)}" + (f"; checked out at `{wt_by_branch[name]}`" if name in wt_by_branch else ""),
             f"- **Last commit:** {last[0]} by {last[1]} ({age} days ago)",
             f"- **Not in main:** {len(unmerged)} commit(s); main is {behind} commits ahead of this branch"
             + (f"; {len(equivalent)} more already reached main another way" if equivalent else ""),
             ]
    try:
        new, clash = decision_changes(git(["show", f"{ref}:DECISIONS.md"], root, check=False),
                                      main_decisions)
    except RuntimeError:
        new, clash = [], []
    for n, t in new:
        lines.append(f"- **Adds decision #{n}:** {t}")
    for n, t, mt in clash:
        lines.append(f"- **⚠️ Decision number clash #{n}:** the branch uses it for \"{t}\"; "
                     f"main already uses it for \"{mt}\". Renumber before merging.")
    lines += ["", "**Commits not in main (oldest first):**", ""]
    for sha in unmerged:
        info = git(["log", "-1", "--format=%h|%ad|%s", "--date=short", sha], root).strip().split("|", 2)
        body = git(["log", "-1", "--format=%b", sha], root)
        body = [b for b in body.splitlines()
                if b.strip() and not re.match(r"^(Co-Authored-By|Claude-Session|Signed-off-by):", b)]
        lines.append(f"- `{info[0]}` {info[1]} — {info[2]}")
        for b in body[:BODY_LINES]:
            lines.append(f"  > {b.strip()}")
        if len(body) > BODY_LINES:
            lines.append(f"  > … ({len(body) - BODY_LINES} more lines: `git show {info[0]}`)")
    base = git(["merge-base", main, ref], root).strip()
    stat = git(["diff", "--stat=100", base, ref], root).rstrip().splitlines()
    if stat:
        lines += ["", f"**Files changed vs. where it left main ({stat[-1].strip()}):**", ""]
        for s in stat[:-1][:MAX_FILES]:
            lines.append(f"    {s.strip()}")
        if len(stat) - 1 > MAX_FILES:
            lines.append(f"    … and {len(stat) - 1 - MAX_FILES} more")
    return "\n".join(lines)


def uncommitted_section(root, trees):
    lines = []
    for t in trees:
        if not Path(t["path"]).is_dir():
            continue
        status = git(["status", "--short"], Path(t["path"]), check=False).splitlines()
        changed = [s for s in status if not s.startswith("??")]
        if not changed:
            continue
        lines.append(f"- `{t['path']}` on `{t['branch']}`: {len(changed)} uncommitted file(s)")
        for s in changed[:MAX_FILES]:
            lines.append(f"  - `{s[3:]}` ({s[:2].strip()})")
    return lines


def build(root=ROOT, main="origin/main", today=None):
    today = today or date.today()
    try:
        git(["rev-parse", "--verify", main], root)
    except RuntimeError:
        main = "main"
    trees = worktrees(root)
    wt_by_branch = {t["branch"]: t["path"] for t in trees}
    main_decisions = git(["show", f"{main}:DECISIONS.md"], root, check=False)
    sections, merged = [], []
    for name, ref, where in list_branches(root, main):
        s = branch_section(root, main, name, ref, where, wt_by_branch, main_decisions, today)
        (sections if s else merged).append(s or name)
    main_head = git(["log", "-1", "--format=%h %ad", "--date=short", main], root).strip()
    out = [f"## Snapshot {today.isoformat()} (compared against `{main}` at {main_head})", "",
           f"**{len(sections)} branch(es) hold work not in main.** "
           "STALE = no commit for over 30 days: probably abandoned or superseded; "
           "read it before merging or deleting.", ""]
    out += [x + "\n" for x in sections] or ["None."]
    out += ["", "## Uncommitted edits in checkouts on this machine", ""]
    out += uncommitted_section(root, trees) or ["None."]
    out += ["", "## Branches with nothing left to merge", "",
            (", ".join(f"`{m}`" for m in sorted(merged)) or "None.")
            + "  \nEverything on these is already in main; they are safe to delete once nobody is using them."]
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--no-fetch", action="store_true", help="skip `git fetch origin`")
    p.add_argument("--stdout", action="store_true", help="print instead of writing docs/BRANCHES.md")
    a = p.parse_args(argv)
    if not a.no_fetch:
        r = subprocess.run(["git", "fetch", "-q", "--prune", "origin"], cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            print(f"branch_report: fetch failed, using cached remote refs ({r.stderr.strip()})", file=sys.stderr)
    auto = build()
    if a.stdout:
        print(auto)
        return 0
    existing = OUT.read_text() if OUT.exists() else ""
    OUT.write_text(splice(existing, auto))
    print(f"branch_report: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
