    assert list((tmp_path / "participant_oi" / "date=2026-10-16").glob("fao_participant_oi*.csv*"))
    miss = poi.run("2026-10-20", root=tmp_path, fetch_fn=lambda d: (404, None))
    assert not miss["written"] and "holiday" in miss["reason"] and poi.load("2026-10-20", root=tmp_path) is None
    assert poi.url_for("2026-10-16").endswith("fao_participant_oi_16102026.csv")


