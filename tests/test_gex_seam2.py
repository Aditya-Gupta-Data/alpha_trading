def test_the_nse_file_parses_balances_and_yields_dealer_weights():
    p = poi.parse(CSV)
    assert p["reason"] is None and p["balanced"] is True
    assert p["rows"]["Client"]["opt_stock_call_long"] == 2_396_725
    w = poi.sign_weights(p, "non_client")
    assert w["stock"]["call"] == pytest.approx(-(2_396_725 - 1_365_136) / 3_831_360, abs=1e-6)
    assert w["index"]["put"] == pytest.approx((4_682_637 - 4_191_151) / 6_846_605, abs=1e-6)
    assert poi.sign_weights(p, "pro")["index"]["call"] == pytest.approx((1_223_426 - 1_014_951) / 5_765_109, abs=1e-6)
    assert poi.sign_weights(p, "nobody") is None
    assert poi.parse("Client Type,x\nClient,1\n")["reason"]


def test_run_archives_the_file_and_writes_one_row(tmp_path):
    out = poi.run("2026-10-16", root=tmp_path, fetch_fn=lambda d: (200, CSV.encode()))
    assert out["written"] and out["balanced"]
    row = poi.load("2026-10-16", root=tmp_path)
