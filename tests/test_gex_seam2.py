def test_the_gex_backfill_adds_repriced_and_calibrated_profiles(tmp_path):
    spec = importlib.util.spec_from_file_location("backfill_gex", ROOT / "scripts" / "backfill_gex_profiles.py")
    bf = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bf)
    root = tmp_path / "lake"
    lake.write_partition("chains/tcs", "2026-10-16", [
        {"underlying": "TCS.NS", "expiry": EXPIRY, "spot": 100.0, "captured_at": AS_OF,
         "oc": _oc(call_oi={100: 900_000, 102: 900_000})}], root=root)
    bare = bf.run(root=root, dry_run=True)["tcs"][0]
    assert bare["combined"]["repriced"]["regime_at_spot"] == "positive" and bare["combined"]["calibrated"] == {}
    poi.run("2026-10-16", root=root, fetch_fn=lambda d: (200, CSV.encode()))
    row = bf.run(root=root, participant_root=root)["tcs"][0]
    cal = row["combined"]["calibrated"]
    assert set(cal) == set(poi.DEALERS) and cal["non_client"]["regime_at_spot"] == "negative"
    assert row["option_class"] == "stock" and row["expiries"][0]["calibrated"]["weights"]["call"] < 0
    assert any(line.startswith("tcs") for line in bf.summary_lines({"tcs": [row]}))
