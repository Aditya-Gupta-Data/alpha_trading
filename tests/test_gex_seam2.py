def test_bs_gamma_matches_the_textbook_and_refuses_bad_inputs():
    assert gp.bs_gamma(100, 100, 20, 30 / 365) == pytest.approx(0.069063, abs=1e-5)
    for bad in ((0, 100, 20, 0.1), (100, 100, 0, 0.1), (100, 100, 20, 0), (100, None, 20, 0.1)):
        assert gp.bs_gamma(*bad) is None


def test_years_to_expiry_runs_to_the_1530_close():
    t = gp.years_to_expiry("2026-10-19", "2026-10-16T15:40:00+05:30")
    assert t * 365 == pytest.approx(3 - 10 / 1440, abs=1e-6)
    assert gp.years_to_expiry("2026-10-16", "2026-10-16T15:40:00+05:30") is None
    assert gp.years_to_expiry("2026-10-19", "2026-10-16T15:40:00") == pytest.approx(t)   # naive = IST


def _oc(spot=100.0, iv=20.0, t=None, call_oi=None, put_oi=None, broken_itm=True):
    """Strikes 80..120 step 2; Dhan gammas generated by Black-Scholes at `spot`; ITM calls carry Dhan's EOD
    zero-IV rows when `broken_itm`."""
    t = t or gp.years_to_expiry(EXPIRY, AS_OF)
    oc = {}
    for k in range(80, 122, 2):
        g = gp.bs_gamma(spot, k, iv, t)
        ce = {"oi": (call_oi or {}).get(k, 10_000), "implied_volatility": iv, "greeks": {"gamma": g}}
        if broken_itm and k < spot:
            ce = {"oi": ce["oi"], "implied_volatility": 0, "greeks": {"gamma": 0}}
        pe = {"oi": (put_oi or {}).get(k, 10_000), "implied_volatility": iv, "greeks": {"gamma": g}}
        oc[f"{k:.6f}"] = {"ce": ce, "pe": pe}
    return oc


def test_dhans_zero_iv_rows_are_missing_not_zero_gamma():
    rows = {r["strike"]: r for r in gp.strike_gex(_oc(), 100.0)}
    assert rows[90.0]["call_gex"] is None and rows[90.0]["complete"] is False
    assert rows[110.0]["complete"] is True


def test_the_otm_side_sets_each_strikes_iv_and_the_model_agrees_with_dhan():
    inputs = {r["strike"]: r for r in gp.strike_inputs(_oc(), 100.0)}
    assert inputs[90.0]["iv_source"] == "pe" and inputs[110.0]["iv_source"] == "ce"
    assert inputs[90.0]["iv"] == 20.0                                  # the broken ITM call IV is never used
    t = gp.years_to_expiry(EXPIRY, AS_OF)
    assert gp.model_gamma_ratio(list(inputs.values()), 100.0, t) == pytest.approx(1.0, abs=1e-3)


def test_the_repriced_zero_gamma_level_sits_between_put_and_call_open_interest():
    oc = _oc(call_oi={104: 400_000, 106: 400_000}, put_oi={94: 400_000, 96: 400_000})
    p = gp.repriced_profile([(oc, EXPIRY)], 100.0, AS_OF, 10.0)
    assert p["zero_gamma"] is not None and 94.0 < p["zero_gamma"] < 106.0
    assert p["zero_gamma_within_grid"] and p["iv_coverage"] == 1.0 and p["model_gamma_ratio"] == pytest.approx(1.0, abs=1e-3)
    below = gp.repriced_profile([(oc, EXPIRY)], 95.0, AS_OF, 10.0)
    above = gp.repriced_profile([(oc, EXPIRY)], 105.0, AS_OF, 10.0)
    assert below["regime_at_spot"] == "negative" and above["regime_at_spot"] == "positive"


def test_calibrated_weights_can_reverse_the_naive_regime():
    oc = _oc(call_oi={100: 900_000, 102: 900_000, 104: 900_000})
    naive = gp.repriced_profile([(oc, EXPIRY)], 100.0, AS_OF, 10.0)
    short_calls = gp.repriced_profile([(oc, EXPIRY)], 100.0, AS_OF, 10.0, {"call": -0.269, "put": 0.054})
    assert naive["regime_at_spot"] == "positive" and short_calls["regime_at_spot"] == "negative"
    assert short_calls["weights"] == {"call": -0.269, "put": 0.054}
    assert short_calls["call_wall"] == naive["call_wall"]              # walls are by size, not by sign


def test_no_usable_chain_abstains_by_name():
    p = gp.repriced_profile([({}, EXPIRY)], 100.0, AS_OF, 10.0)
    assert p["regime"] is None and p["reason"] and p["zero_gamma"] is None


